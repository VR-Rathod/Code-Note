// components for pages that display a single page (e.g. a single note)
export const defaultContentPageLayout: PageLayout = {
  beforeBody: [
    Component.ConditionalRender({
      component: Component.Breadcrumbs(),
      condition: (page) => page.fileData.slug !== "index",
    }),
    Component.ArticleTitle(),
    Component.ContentMeta(),
    Component.TagList(),
  ],
  left: [
    Component.PageTitle(),
    Component.MobileOnly(Component.Spacer()),
    Component.Flex({
      components: [
        {
          Component: Component.Search(),
          grow: true,
        },
        { Component: Component.Darkmode() },
        { Component: Component.ReaderMode() },
      ],
    }),
    Component.Explorer(),
  ],
  right: [
    Component.Graph({
      localGraph: {
        drag: true,
        zoom: true,
        depth: 1,        // only direct neighbors — keeps it clean
        scale: 1.2,
        repelForce: 0.8, // push nodes apart so labels don't overlap
        centerForce: 0.4,
        linkDistance: 50, // more breathing room between nodes
        fontSize: 0.45,
        opacityScale: 1,
        showTags: false,  // hide tag nodes — reduces clutter
      },
      globalGraph: {
        drag: true,
        zoom: true,
        depth: 2,         // limit global graph depth too
        scale: 0.7,
        repelForce: 0.6,
        centerForce: 0.3,
        linkDistance: 40,
        fontSize: 0.35,
        opacityScale: 0.8,
        showTags: false,
      },
    }),
    Component.DesktopOnly(Component.TableOfContents()),
    Component.Backlinks(),
  ],
}

